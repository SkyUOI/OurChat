import 'package:flutter/material.dart';
import 'package:ourchat/main.dart';

import 'sticker_panel.dart';

/// Hand-written emoji picker panel (issue #248), extended with a stickers
/// tab holding the user's private collection (issue #147).
///
/// Uses only plain Unicode constants so it works on every platform,
/// including web, without any third-party emoji package. When
/// [onStickerSelected] is null (e.g. in tests) the panel stays emoji-only.
class EmojiPanel extends StatefulWidget {
  const EmojiPanel({
    super.key,
    required this.onEmojiSelected,
    this.onStickerSelected,
  });

  /// Called every time the user taps an emoji. The panel stays open so
  /// several emoji can be inserted in a row.
  final ValueChanged<String> onEmojiSelected;

  /// Called with the server-side file key of the tapped sticker (issue #147).
  final ValueChanged<String>? onStickerSelected;

  @override
  State<EmojiPanel> createState() => _EmojiPanelState();
}

class _EmojiPanelState extends State<EmojiPanel> {
  int _categoryIndex = 0;

  List<String> _categoryLabels() => [
    l10n.emojiCategorySmileys,
    l10n.emojiCategoryPeople,
    l10n.emojiCategoryAnimals,
    l10n.emojiCategoryFood,
    l10n.emojiCategoryActivities,
    l10n.emojiCategoryObjects,
  ];

  @override
  Widget build(BuildContext context) {
    final emojiView = _buildEmojiView();
    if (widget.onStickerSelected == null) {
      // Emoji-only panel (tests, or callers that cannot send stickers).
      return Material(elevation: 0, child: emojiView);
    }
    return Material(
      elevation: 0,
      child: DefaultTabController(
        length: 2,
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            TabBar(
              isScrollable: true,
              tabAlignment: TabAlignment.start,
              tabs: [
                Tab(text: l10n.emoji),
                Tab(text: l10n.stickersTab),
              ],
            ),
            Expanded(
              child: TabBarView(
                children: [
                  emojiView,
                  StickerPanel(onStickerSelected: widget.onStickerSelected!),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildEmojiView() {
    final labels = _categoryLabels();
    final emojis = emojiCategories[_categoryIndex];
    return Column(
      mainAxisSize: MainAxisSize.min,
      children: [
        SizedBox(
          height: 36,
          child: ListView.builder(
            scrollDirection: Axis.horizontal,
            itemCount: labels.length,
            itemBuilder: (context, index) {
              final selected = index == _categoryIndex;
              return Padding(
                padding: const EdgeInsets.symmetric(horizontal: 2.0),
                child: ChoiceChip(
                  label: Text(
                    labels[index],
                    style: const TextStyle(fontSize: 12),
                  ),
                  selected: selected,
                  onSelected: (_) => setState(() => _categoryIndex = index),
                  visualDensity: VisualDensity.compact,
                ),
              );
            },
          ),
        ),
        const Divider(height: 1),
        Expanded(
          child: GridView.builder(
            padding: const EdgeInsets.all(4.0),
            gridDelegate: SliverGridDelegateWithMaxCrossAxisExtent(
              maxCrossAxisExtent: 44,
              mainAxisSpacing: 2,
              crossAxisSpacing: 2,
            ),
            itemCount: emojis.length,
            itemBuilder: (context, index) {
              final emoji = emojis[index];
              return InkWell(
                borderRadius: BorderRadius.circular(6),
                onTap: () => widget.onEmojiSelected(emoji),
                child: Center(
                  child: Text(
                    emoji,
                    style: const TextStyle(fontSize: 24),
                    textScaler: TextScaler.noScaling,
                  ),
                ),
              );
            },
          ),
        ),
      ],
    );
  }
}
